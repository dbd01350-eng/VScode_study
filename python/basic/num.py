# 숫자자료형
## 정수 : 소수점없는 숫자 int
## 실수 : 소수점있는 숫자 float
## 복소수 : 실수 + 허수 조합   complex

a = 10
b = 3

print(a + b)  # 13
print(a - b)  # 7
print(a * b)  # 30
print(a / b)  # 3.3333...
print(a // b)  # 몫 3
print(a % b)  # 나머지 1
print(a**b)  # 10의 3승 1000

# 자료형변환
c = int(3.3)
print(c)
d = int(5 / 2)
print(d)
print(int("10"))
# 자료형확인
print(type(d))
print(type("d"))
